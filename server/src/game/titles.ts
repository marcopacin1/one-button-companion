export type TitleSource = "level" | "coins" | "achievement";

export interface TitleInfo {
  id: string;
  source: TitleSource;
  reason: string;
}

const fmt = (n: number) => n.toLocaleString("en-US");

export const TITLES: ReadonlyMap<string, TitleInfo> = new Map<string, TitleInfo>([
  ...LEVEL_TITLES.map(([id, level]): [string, TitleInfo] => [
    id,
    { id, source: "level", reason: `Reach level ${level}` },
  ]),
  ...COIN_TITLES.map(([id, coins]): [string, TitleInfo] => [
    id,
    { id, source: "coins", reason: `Hold ${fmt(coins)} coins` },
  ]),
  ...ACHIEVEMENT_TITLES.map(([id, reason]): [string, TitleInfo] => [
    id,
    { id, source: "achievement", reason },
  ]),
]);
